let capituloActual = 1;

function imgOrPlaceholder(src, alt, placeholderText) {
  return `<img src="${src}" alt="${alt}" loading="lazy"
    onerror="this.onerror=null;this.replaceWith(Object.assign(document.createElement('span'),{className:'ph-fallback',textContent:'${placeholderText}'}))">`;
}

function renderizarNavCapitulos() {
  const nav = document.getElementById("navChapters");
  const claves = Object.keys(capitulos)
    .map(Number)
    .sort((a, b) => a - b);
  nav.innerHTML = claves
    .map((n) => {
      const activo = n === capituloActual ? " on" : "";
      return `<span class="chapter-link${activo}" data-cap="${n}">Cap. ${n}</span>`;
    })
    .join("");
  nav.querySelectorAll(".chapter-link").forEach((el) => {
    el.addEventListener("click", () => cambiarCapitulo(Number(el.dataset.cap)));
  });
}

function cambiarCapitulo(n) {
  if (!capitulos[n]) return;
  capituloActual = n;
  renderizarCapitulo();
  renderizarNavCapitulos();
  window.scrollTo({ top: 0, behavior: "smooth" });
}

function renderizarCapitulo() {
  const cap = capitulos[capituloActual];
  const root = document.getElementById("chapterRoot");

  const sinopsisHtml = cap.sinopsis
    .map(
      (p) =>
        `<p class="${p.trim().startsWith("—") ? "dialogue" : ""}">${p}</p>`,
    )
    .join("");

  const repartoHtml = cap.reparto
    .map(
      (p) => `
      <div class="cast-card">
        <div class="cast-photo">${imgOrPlaceholder(p.foto, p.nombre, "[ foto ]")}</div>
        <div class="cast-name">${p.nombre}</div>
        <div class="cast-role">${p.rol}</div>
      </div>`,
    )
    .join("");

  const packs = [];
  for (let i = 0; i < cap.momentos.length; i += 3) {
    packs.push(cap.momentos.slice(i, i + 3));
  }
  const momentosHtml = packs
    .map((pack) => {
      const claseExtra =
        pack.length === 1
          ? " gallery-pack-single"
          : pack.length === 2
            ? " gallery-pack-pair"
            : "";
      const itemsHtml = pack
        .map(
          (m, idx) => `
      <div class="g-item${idx === 0 ? " g-main" : ""}">
        ${imgOrPlaceholder(m.foto, m.titulo, "[ imagen ]")}
        <span>${m.titulo}</span>
      </div>`,
        )
        .join("");
      return `<div class="gallery-pack${claseExtra}">${itemsHtml}</div>`;
    })
    .join("");

  root.innerHTML = `
    <div class="hero">
      <div class="particles" id="particles"></div>
      <div class="kicker reveal d1">TEMPORADA ${cap.temporada} · <b>CAPÍTULO ${cap.numero}</b></div>
      <h1 class="title reveal d2">${cap.titulo}</h1>
      <p class="subtitle reveal d3">${cap.subtitulo}</p>
      <div class="tagline reveal d4">${cap.tagline}</div>
      <div class="poster-frame reveal d5">
        ${imgOrPlaceholder(cap.poster, cap.titulo, "[ cartel promocional del capítulo ]")}
      </div>
    </div>

    <section class="synopsis">
      <div class="eyebrow">SINOPSIS</div>
      <div class="synopsis-inner">${sinopsisHtml}</div>
    </section>

    <div class="pullquote">
      <p>«${cap.cita.texto}»</p>
      <cite>— ${cap.cita.autor}</cite>
    </div>

    <section>
      <div class="eyebrow">REPARTO DE ESTE CAPÍTULO</div>
      <div class="cast-grid">${repartoHtml}</div>
    </section>

    <section>
      <div class="eyebrow">MOMENTOS DEL CAPÍTULO</div>
      <div class="gallery-packs">${momentosHtml}</div>
    </section>

    <div class="next">
      <div class="eyebrow">PRÓXIMO CAPÍTULO</div>
      <h3>${cap.siguiente.titulo}</h3>
      <div class="next-date">${cap.siguiente.fecha}</div>
    </div>
  `;

  if (typeof iniciarParticulas === "function") iniciarParticulas();
}

document.addEventListener("DOMContentLoaded", () => {
  renderizarNavCapitulos();
  renderizarCapitulo();
});
